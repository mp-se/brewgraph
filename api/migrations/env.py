import os

from core.models import Base
# oss/models/__init__.py is the single place the module list lives — main_oss.py
# imports the same modules rather than keeping its own copy.
import oss.models as _oss_models  # noqa: F401
import oss.models.platform as _platform  # noqa: F401

target_metadata = Base.metadata

# Override sqlalchemy.url from DATABASE_URL env var if set
_db_url = os.environ.get("DATABASE_URL")
if _db_url:
    config.set_main_option("sqlalchemy.url", _db_url)

