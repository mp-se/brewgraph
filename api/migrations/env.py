from logging.config import fileConfig

from sqlalchemy import engine_from_config
from sqlalchemy import pool

from alembic import context

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Interpret the config file for Python logging.
# This line sets up loggers basically.
if config.config_file_name is not None:
    # disable_existing_loggers=False is deliberate. The default (True) switches off
    # every logger that already exists when alembic configures logging — including
    # the application's own. In-process callers (the pytest suite, any code running
    # a migration at startup) would silently lose all application logging from that
    # point on.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

